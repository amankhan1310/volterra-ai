@dataclass
class ServerState:
    files: dict[str, bytes] = field(default_factory=dict)
    #: Per path, a queue of faults applied to successive requests:
    #: "truncate" (send half the body then close), "ignore-range", "500", "404", "416".
    faults: dict[str, list[str]] = field(default_factory=dict)
    requests: list[tuple[str, str | None]] = field(default_factory=list)


def _handler(state: ServerState) -> type[BaseHTTPRequestHandler]:
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format: str, *args: object) -> None:  # noqa: A002
            pass

        def do_GET(self) -> None:  # noqa: N802
            path = self.path.lstrip("/")
            rng = self.headers.get("Range")
            state.requests.append((path, rng))
            fault = state.faults.get(path, []).pop(0) if state.faults.get(path) else None
            if path.startswith("redirect/"):
                self.send_response(302)
                self.send_header("Location", "/" + path.removeprefix("redirect/"))
                self.end_headers()
                return
            if fault in ("500", "404", "416") or path not in state.files:
                self.send_response(int(fault) if fault else 404)
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            body = state.files[path]
            start = 0
            if rng and fault != "ignore-range":
                start = int(rng.removeprefix("bytes=").split("-")[0])
                self.send_response(206)
                self.send_header("Content-Range", f"bytes {start}-{len(body) - 1}/{len(body)}")
            else:
                self.send_response(200)
            chunk = body[start:]
            self.send_header("Content-Length", str(len(chunk)))
            self.send_header("ETag", '"' + hashlib.md5(body).hexdigest() + '"')  # noqa: S324
            self.send_header("Last-Modified", "Mon, 10 Aug 2015 14:37:18 GMT")
            self.end_headers()
            if fault == "truncate":
                self.wfile.write(chunk[: len(chunk) // 2])
                self.wfile.flush()
                self.close_connection = True
                return
            self.wfile.write(chunk)

    return Handler


@dataclass
class Server:
    state: ServerState
    base: str

    def url(self, name: str) -> str:
        return f"{self.base}/{name}"


@pytest.fixture
def server() -> Iterator[Server]:
    state = ServerState()
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), _handler(state))
    thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    thread.start()
    try:
        yield Server(state, f"http://127.0.0.1:{httpd.server_address[1]}")
    finally:
        httpd.shutdown()
        httpd.server_close()


def payload(seed: int, size: int = 300_000) -> bytes:
    """Deterministic pseudo-random bytes (not real data)."""
    out = bytearray()
    block = seed.to_bytes(8, "big")
    while len(out) < size:
        block = hashlib.sha256(block).digest()
        out += block
    return bytes(out[:size])


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def remote(name: str, url: str, data: bytes | None = None, *, pin: bool = False) -> RemoteFile:
    """A RemoteFile; the https check is bypassed for the local test server only."""
    f = RemoteFile(name=name, url="https://example.invalid/" + name, description="test")
    object.__setattr__(f, "url", url)
    if pin and data is not None:
        object.__setattr__(f, "bytes", len(data))
        object.__setattr__(f, "sha256", sha(data))
    return f


