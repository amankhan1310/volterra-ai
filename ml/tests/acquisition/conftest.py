"""A real local HTTP server with Range support and fault injection, plus a tiny test registry.

No test touches the network or a real dataset: the payloads are random bytes generated here.
"""

from __future__ import annotations

import hashlib
import threading
from collections.abc import Iterator
from dataclasses import dataclass, field
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import pytest

